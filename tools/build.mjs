// Generate every consumer format in dist/ from the sources in themes/.
//
//   node tools/build.mjs           write dist/
//   node tools/build.mjs --check   write nothing; exit 1 if dist/ is stale
//
// dist/ is COMMITTED, so a consumer needs no node and no build step: the
// website copies a file, a Wii Makefile adds an include path. The cost of that
// is that dist/ can fall behind themes/, and --check is what CI runs to stop it.
//
// Outputs, all derived and none to be edited by hand:
//   themes.json     the website's arcade/admin/themes.json, reproduced exactly
//   themes.css      role and palette custom properties, scoped per theme
//   themes.mjs      the same data as an ES module
//   magma_themes.h  C macros for magnolia and GRRLIB, with TV-safe variants
//   tv-report.txt   which colours were pulled in for NTSC composite, and by how much

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import {
  DIST_DIR, ROLES, loadThemes, validate, colourOf, tvSafe, tvSignal, TV_PEAK, TV_TROUGH,
} from './lib.mjs';

const check = process.argv.includes('--check');
const themes = loadThemes();
const errors = validate(themes);
if (errors.length) {
  for (const e of errors) console.error(e);
  console.error(`${errors.length} problem(s) in themes/; nothing written.`);
  process.exit(2);
}
const painted = themes.filter((t) => t.palette.length);

// A palette entry's name with its `--` and section prefix removed, which is
// what every output except themes.json uses: `--svfp-bg` becomes `bg`.
function bare(t, v) {
  let s = v.replace(/^--/, '');
  const p = t.web && t.web.prefix;
  if (p && s.startsWith(`${p}-`)) s = s.slice(p.length + 1);
  return s;
}

const HEADER = 'GENERATED by tools/build.mjs from themes/. Do not edit; edit the source and rebuild.';

// ---- themes.json -----------------------------------------------------------

function websiteJson() {
  const out = themes.map((t) => {
    const w = t.web;
    const o = { name: t.name, section: w.section, bodyClass: w.bodyClass, prefix: w.prefix, file: w.file };
    if ('dataTheme' in w) o.dataTheme = w.dataTheme;
    o.palette = t.palette;
    o.nav = w.nav;
    return o;
  });
  return JSON.stringify(out, null, 2) + '\n';
}

// ---- themes.css ------------------------------------------------------------

function css() {
  const lines = [
    `/* ${HEADER}`,
    ' *',
    ' * Opt in with an attribute on any element:  <body data-magma-theme="memphis">',
    ' * Roles a theme lacks are simply absent, so give every var() a fallback.',
    ' *',
    ' *   --mt-<role>     one of ' + ROLES.join(', '),
    ' *   --mt-p-<name>   every palette entry, under its unprefixed name',
    ' */',
    '',
  ];
  for (const t of painted) {
    lines.push(`/* ${t.name} */`);
    lines.push(`[data-magma-theme="${t.slug}"] {`);
    for (const r of ROLES) if (t.roles[r]) lines.push(`  --mt-${r}: ${colourOf(t, t.roles[r]).toLowerCase()};`);
    for (const p of t.palette) lines.push(`  --mt-p-${bare(t, p.var)}: ${p.value.toLowerCase()};`);
    lines.push('}', '');
  }
  return lines.join('\n');
}

// ---- themes.mjs ------------------------------------------------------------

function mjs() {
  const data = {};
  for (const t of painted) {
    const roles = {};
    for (const r of ROLES) if (t.roles[r]) roles[r] = colourOf(t, t.roles[r]).toLowerCase();
    const palette = {};
    for (const p of t.palette) palette[bare(t, p.var)] = p.value.toLowerCase();
    data[t.slug] = { name: t.name, roles, palette };
  }
  return [
    `// ${HEADER}`,
    '',
    `export const ROLES = ${JSON.stringify(ROLES)};`,
    '',
    `export const THEMES = ${JSON.stringify(data, null, 2)};`,
    '',
    '// Set every --mt-* property of a theme on an element (default: the root).',
    'export function applyTheme(slug, el = document.documentElement) {',
    '  const t = THEMES[slug];',
    "  if (!t) throw new Error(`unknown theme: ${slug}`);",
    '  for (const [k, v] of Object.entries(t.roles)) el.style.setProperty(`--mt-${k}`, v);',
    '  for (const [k, v] of Object.entries(t.palette)) el.style.setProperty(`--mt-p-${k}`, v);',
    '}',
    '',
  ].join('\n');
}

// ---- magma_themes.h --------------------------------------------------------

const cid = (s) => s.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_|_$/g, '');
const rgba = (hex) => `0x${hex.slice(1).toLowerCase()}ffu`;

function header() {
  const lines = [
    `/* ${HEADER}`,
    ' *',
    ' * Colours are 0xRRGGBBAA, which is what GRRLIB takes, fully opaque.',
    ' *',
    ' *   MT_<THEME>_<ROLE>         a role, as the theme designed it',
    ' *   MT_<THEME>_<ROLE>_TV      the same, pulled in for NTSC composite',
    ' *   MT_<THEME>_P_<NAME>       a palette entry, and _TV likewise',
    ' *',
    ' * Use the _TV form for anything drawn on a console. It equals the plain one',
    ' * whenever the colour was already safe, so there is no cost to defaulting',
    ' * to it; tv-report.txt lists the ones that moved.',
    ' */',
    '#ifndef MAGMA_THEMES_H',
    '#define MAGMA_THEMES_H',
    '',
  ];
  for (const t of painted) {
    const T = cid(t.slug);
    lines.push(`/* ${t.name} */`);
    const seen = new Set();
    const emit = (name, hex) => {
      if (seen.has(name)) throw new Error(`${t.slug}: two entries become C name ${name}`);
      seen.add(name);
      lines.push(`#define ${name} ${rgba(hex)}`);
      lines.push(`#define ${name}_TV ${rgba(tvSafe(hex))}`);
    };
    for (const r of ROLES) if (t.roles[r]) emit(`MT_${T}_${cid(r)}`, colourOf(t, t.roles[r]));
    for (const p of t.palette) emit(`MT_${T}_P_${cid(bare(t, p.var))}`, p.value);
    lines.push('');
  }
  lines.push('#endif /* MAGMA_THEMES_H */', '');
  return lines.join('\n');
}

// ---- tv-report.txt ---------------------------------------------------------

function tvReport() {
  const pct = (v) => `${Math.round(v * 100)}`.padStart(4);
  const rows = [];
  let total = 0;
  for (const t of painted) {
    for (const p of t.palette) {
      total++;
      const safe = tvSafe(p.value);
      if (safe === p.value.toLowerCase()) continue;
      const s = tvSignal(p.value);
      rows.push(
        `${t.slug.padEnd(26)} ${bare(t, p.var).padEnd(22)} ${p.value.toLowerCase()} -> ${safe}` +
          `   peak ${pct(s.peak)} trough ${pct(s.trough)} IRE`,
      );
    }
  }
  return [
    HEADER,
    '',
    `NTSC composite limits: peak ${Math.round(TV_PEAK * 100)} IRE, trough ${Math.round(TV_TROUGH * 100)} IRE.`,
    `${rows.length} of ${total} palette colours exceed them and have a pulled-in _TV form.`,
    'Luma is kept; only saturation is reduced. Peak and trough are the ORIGINAL colour.',
    '',
    ...rows,
    '',
  ].join('\n');
}

// ---- write or check --------------------------------------------------------

const outputs = {
  'themes.json': websiteJson(),
  'themes.css': css(),
  'themes.mjs': mjs(),
  'magma_themes.h': header(),
  'tv-report.txt': tvReport(),
};

console.log(`${themes.length} themes, ${painted.length} with colours, ${Object.keys(outputs).length} outputs.`);

if (check) {
  const stale = Object.entries(outputs).filter(([f, body]) => {
    const p = join(DIST_DIR, f);
    // CRLF is folded because a Windows clone with core.autocrlf checks dist/
    // out as CRLF while the index, and this output, are LF.
    return !existsSync(p) || readFileSync(p, 'utf8').replace(/\r\n/g, '\n') !== body;
  });
  if (stale.length) {
    for (const [f] of stale) console.error(`STALE dist/${f}`);
    console.error('dist/ does not match themes/. Run: node tools/build.mjs');
    process.exit(1);
  }
  console.log(`dist/ is current: compared ${Object.keys(outputs).length} of ${Object.keys(outputs).length} files.`);
} else {
  mkdirSync(DIST_DIR, { recursive: true });
  for (const [f, body] of Object.entries(outputs)) writeFileSync(join(DIST_DIR, f), body);
  console.log(`wrote dist/: ${Object.keys(outputs).join(', ')}`);
}
